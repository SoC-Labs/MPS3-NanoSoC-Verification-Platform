GPIO_NGPIO_DEFAULT = 16  # partition-pins.md board-port group: "v0: 16"


class AxiLiteMaster:
    """Minimal self-contained AXI4-Lite master BFM (no cocotbext-axi
    dependency). One in-flight transaction at a time — plenty for
    register-poke benches.
    """

    def __init__(self, clk, awaddr, awvalid, awready, wdata, wstrb, wvalid,
                 wready, bresp, bvalid, bready, araddr, arvalid, arready,
                 rdata, rresp, rvalid, rready):
        self.clk = clk
        self.awaddr, self.awvalid, self.awready = awaddr, awvalid, awready
        self.wdata, self.wstrb, self.wvalid, self.wready = wdata, wstrb, wvalid, wready
        self.bresp, self.bvalid, self.bready = bresp, bvalid, bready
        self.araddr, self.arvalid, self.arready = araddr, arvalid, arready
        self.rdata, self.rresp, self.rvalid, self.rready = rdata, rresp, rvalid, rready

    @classmethod
    def from_dut(cls, dut, prefix: str = "s_axi_"):
        """Binds directly to the `s_axi_*` ports shared verbatim by
        dut_clkrst.sv / dfx_ctl.sv / mdio_phy_model.sv / gen_checker.sv."""
        g = lambda name: getattr(dut, f"{prefix}{name}")  # noqa: E731
        return cls(
            clk=g("aclk"),
            awaddr=g("awaddr"), awvalid=g("awvalid"), awready=g("awready"),
            wdata=g("wdata"), wstrb=g("wstrb"), wvalid=g("wvalid"), wready=g("wready"),
            bresp=g("bresp"), bvalid=g("bvalid"), bready=g("bready"),
            araddr=g("araddr"), arvalid=g("arvalid"), arready=g("arready"),
            rdata=g("rdata"), rresp=g("rresp"), rvalid=g("rvalid"), rready=g("rready"),
        )

    # The two slave styles this BFM must serve (verified by reading the RTL):
    #   - Xilinx-template FSM (dfx_ctl/dut_clkrst/board_gpio): ready pulses
    #     one cycle, THEN bvalid/rvalid assert one cycle later.
    #   - accept-on-valid (mdio_phy_model.sv): awready+bvalid (and
    #     arready+rvalid) are registered high at the SAME edge.
    # So ready observation and response capture must run CONCURRENTLY (a
    # sequential ready-then-response wait misses the mdio-style response
    # pulse and hangs — found the hard way under VCS). VALID/READY drives
    # are held through the clock edge that retires the last handshake, then
    # deasserted in that edge's writable window.

    async def write(self, addr: int, data: int, strb: int = 0xF) -> int:
        self.awaddr.value = addr
        self.awvalid.value = 1
        self.wdata.value = data
        self.wstrb.value = strb
        self.wvalid.value = 1
        self.bready.value = 1
        aw_seen = w_seen = False
        resp = None
        while resp is None or not (aw_seen and w_seen):
            await RisingEdge(self.clk)
            await ReadOnly()
            aw_seen = aw_seen or bool(int(self.awready.value))
            w_seen = w_seen or bool(int(self.wready.value))
            if resp is None and int(self.bvalid.value):
                resp = int(self.bresp.value)  # BREADY is held high throughout
        await RisingEdge(self.clk)  # last-observed handshake retires here
        self.awvalid.value = 0      # writable phase (post-edge callback)
        self.wvalid.value = 0
        self.bready.value = 0
        return resp

    async def write_bytes(self, addr: int, data: int, strb: int) -> int:
        """WSTRB-aware write: drive `data` with an explicit byte-lane strobe
        `strb` (bit i enables wdata[8*i +: 8]). Thin, self-documenting wrapper
        over write() — write() always drove strb=0xF (a full-word write), so
        every AXI4-Lite slave's per-lane WSTRB decode went UNTESTED until this
        entry point existed. A slave that ignores WSTRB (commits the whole
        word regardless of the strobe) is caught by the per-block
        `test_wstrb_*` benches that drive partial strobes through here and
        assert only the enabled lanes changed.

        `strb=0` is a legal, no-lane write (a bare address touch): the AXI-Lite
        transaction still completes with BRESP=OKAY, and a correct slave leaves
        every register byte unchanged.
        """
        return await self.write(addr, data, strb)

    async def read(self, addr: int):
        self.araddr.value = addr
        self.arvalid.value = 1
        self.rready.value = 1
        ar_seen = False
        data = resp = None
        while data is None or not ar_seen:
            await RisingEdge(self.clk)
            await ReadOnly()
            ar_seen = ar_seen or bool(int(self.arready.value))
            if data is None and int(self.rvalid.value):
                data = int(self.rdata.value)  # RREADY is held high throughout
                resp = int(self.rresp.value)
        await RisingEdge(self.clk)  # last-observed handshake retires here
        self.arvalid.value = 0      # writable phase (post-edge callback)
        self.rready.value = 0
        # One idle edge with ARVALID low before returning (found 2026-07-06
        # while benching swd_bb with ZERO-GAP back-to-back read() calls —
        # the older benches always had at least one await between reads, so
        # this never fired for them): the Xilinx-template FSM re-asserts
        # ARREADY at the retire edge above (ARVALID is still high there)
        # and re-captures the OLD ARADDR into axi_araddr_q. If the caller
        # issues the next read() in this same writable window, ARVALID
        # never dips at a clock edge, that phantom acceptance completes,
        # and the data returned is for the PREVIOUS address. The idle edge
        # kills the phantom (ARREADY falls with ARVALID low, no rden).
        # write() needs no equivalent: its aw_en_q interlock means a
        # zero-gap follow-on write is accepted with the NEW address.
        await RisingEdge(self.clk)
        return data, resp
