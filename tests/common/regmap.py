# cocotb 2.x port note (2026-07-04, W-SIM): the original write()/read() below
# deasserted valid/ready handles *while parked in the ReadOnly phase*, which
# raises "Attempting setting a value during the ReadOnly phase" — under
# cocotb 2.0.1 AND 1.7.2 alike (1.7.2's scheduler.py:596 has the same check;
# this BFM was only ever `make -n` dry-run under 1.7.2, never executed).
# The port keeps the public API (from_dut()/write()/read() signatures and
# return values unchanged) and restructures each call into: sample handshake
# progress in ReadOnly, then perform every signal write in a writable phase
# (immediately after a RisingEdge callback). See the comment above write()
# for the two slave handshake styles this must serve concurrently — the
# Xilinx-template FSMs (dfx_ctl/dut_clkrst/board_gpio) and mdio_phy_model's
# accept-on-valid style (response valid registered at the SAME edge as
# ready) — and why ready observation and response capture are one loop.

