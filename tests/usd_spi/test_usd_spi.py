async def _measure_sck(b, div, nbits, reply=0):
    """Run one shift at `div` with the pads forced on (CD_IGNORE) and a raw
    slave on the pads; return the slave's recording."""
    await b.set_div(div)
    await b.set_ctrl(en=1, cd_ignore=1, wide=(nbits == 32))
    s = RawSpiSlave(b.dut, reply, nbits)
    await b.xfer(0xA5A5_A5A5, wide=(nbits == 32))
    s.stop()
    return s


def _check_period(s, div, nbits):
    half = (div + 1) * CLK_NS
    assert len(s.rise_t) == nbits and len(s.fall_t) == nbits, (
        f"expected {nbits} SCK rising/falling edges, saw {len(s.rise_t)}/{len(s.fall_t)}")
    periods = {round(t1 - t0, 3) for t0, t1 in zip(s.rise_t, s.rise_t[1:])}
    assert periods == {2 * half}, f"SCK period(s) {periods} ns, expected {2 * half} ns"
    highs = {round(f - r, 3) for r, f in zip(s.rise_t, s.fall_t)}
    assert highs == {half}, f"SCK high time(s) {highs} ns, expected {half} ns"
    lows = {round(r - f, 3) for f, r in zip(s.fall_t, s.rise_t[1:])}
    assert not lows or lows == {half}, f"SCK low time(s) {lows} ns, expected {half} ns"


@cocotb.test(skip=NO_RTL)
async def test_sck_period_at_reset_divider(dut):
    """SCK = aclk / (2*(124+1)) = 400 kHz: 2500 ns period, 50 % duty."""
    b = await bring_up(dut)
    s = await _measure_sck(b, CLKDIV_RESET, 8)
    _check_period(s, CLKDIV_RESET, 8)
    assert int(dut.usd_clk_o.value) == 0, "SCK must idle low"


@cocotb.test(skip=NO_RTL)
async def test_sck_period_at_div3_and_faster(dut):
    """DIV=3 -> 12.5 MHz (80 ns), the firmware's post-init speed; also DIV=1
    (25 MHz) and DIV=0 (aclk/2), over a 32-bit shift."""
    b = await bring_up(dut)
    for div in (3, 1, 0):
        s = await _measure_sck(b, div, 32)
        _check_period(s, div, 32)


@cocotb.test(skip=NO_RTL)
async def test_shift_8bit_mode0_msb_first(dut):
    """WIDE=0: only wdata[7:0] goes out, MSB first; MOSI changes only with SCK
    low (on the falling edge, never while SCK is high); RX is zero-extended;
    SCK idles low and MOSI idles high afterwards."""
    b = await bring_up(dut)
    await b.set_div(3)
    await b.set_ctrl(en=1, cd_ignore=1, wide=0)
    s = RawSpiSlave(dut, 0xC3, 8)
    rx = await b.xfer(0xABCD_EF5A)
    s.stop()
    assert s.mosi_word() == 0x5A and len(s.mosi) == 8, f"MOSI {s.mosi}"
    assert rx == 0x0000_00C3, f"RX 0x{rx:08X}"
    for r, f in zip(s.rise_t, s.fall_t):
        inside = [t for t in s.mosi_change_t if r <= t < f]
        assert not inside, f"MOSI moved at {inside} while SCK was high ({r}..{f} ns)"
    assert int(dut.usd_clk_o.value) == 0 and int(dut.usd_cmd_o.value) == 1


