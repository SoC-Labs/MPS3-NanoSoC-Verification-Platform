"""tests/usd_spi/test_usd_spi.py

Verifies `fpga/shell/ip/usd_spi/usd_spi.sv` — USD @ 0x44A4_0000, the SPI-mode
master for the MPS3 USER microSD slot (docs/planning/HANDOVER_USD_OVERLAY_STORE.md
§4.1, §4.7; lane D13-L1).

What this proves, all from the AXI4-Lite side and the pads:
  1. Registers: ID, reset values, byte lanes, W1C, and that unmapped offsets
     read 0 and do not alias — AT THE WIDTH THE BD INSTANTIATES (CFG=bd:
     C_S_AXI_ADDR_WIDTH=32, driven as 0x44A4_0000 + offset) as well as at the
     RTL default (CFG=w12). See the Makefile.
  2. SCK = aclk / (2*(DIV+1)), measured on the pad, at the reset divider (124)
     and at DIV = 3 (plus 1 and 0).
  3. SPI mode 0, MSB first, 8- and 32-bit shifts; MOSI never moves while SCK is
     high; MISO sampled late enough for tODLY + board round trip at 25 MHz.
  4. CS on USD_DAT[3], active low.
  5. THE PAD GATE: every output-enable is 0 when EN=0, when no card is present,
     and CD_IGNORE overrides the card-detect term. (`make control-cd-gate-ignored`
     shows test_pads_hiz_without_card failing on a gate that ignores CD.)
  6. Card detect: 2-FF sync, debounce (a glitch of DEBOUNCE_CYCLES-1 is ignored,
     DEBOUNCE_CYCLES is accepted), CD_CHANGED sticky/W1C, CD_POL, CD_RAW.
  7. ABORT on a mid-transfer card removal (and EN clear); OVR on a DATA write
     while BUSY.
  8. End to end against sd_card_model.SdCardModel, driven ONLY through AXI:
     power-up clocks, CMD0/CMD8/ACMD41/CMD58 init, CMD9, CMD17 read,
     CMD24 write, read-back; CMD18/CMD12 and CMD25 multi-block; the card's
     CRC7 checks on CMD0/CMD8; an SDSC card reporting CCS=0.

The register offsets below are the lane contract, written out here on purpose,
and held equal to tests/common/regmap.py -- GENERATED by tools/gen_regmap.py from
shell_bd.tcl's `;# USD` line and this RTL's IDX_* lines -- at import, so the
bench, the RTL decode and every generated view (platform_regs.h, pyverify,
shell-regmap.md) cannot drift apart. The elaborated address width and debounce
are read back from the DUT, not restated.
"""
