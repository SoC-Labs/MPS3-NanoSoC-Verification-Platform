@cocotb.test(skip=NO_RTL)
async def test_busy_visible_on_first_status_read_after_write(dut):
    """Firmware contract (lane L2): the FIRST STATUS read issued after a DATA
    write's B-response already sees BUSY=1 -- there is no window in which a
    poll straight after the write reads BUSY=0 before the shift has started.
    (BUSY is set on the same aclk edge that accepts the write, and BVALID rises
    on that edge too.) Checked at the tightest case, DIV=0 with an 8-bit shift
    (16 aclk in all), and at the reset divider, in both widths."""
    b = await bring_up(dut)
    await b.set_ctrl(en=1, cd_ignore=1)
    for div in (0, CLKDIV_RESET):
        await b.set_div(div)
        for wide in (0, 1):
            await b.set_ctrl(wide=wide)
            await b.wr(USD_DATA, 0xA5A5_A5A5)
            st = await b.status()                    # the very next transaction
            assert st & ST_BUSY, (
                f"first STATUS read after the DATA write saw BUSY=0 "
                f"(DIV={div}, WIDE={wide}, STATUS=0x{st:02X})")
            st = await b.wait_idle(32 if wide else 8)
            assert not st & (ST_OVR | ST_ABORT), f"0x{st:02X}"


