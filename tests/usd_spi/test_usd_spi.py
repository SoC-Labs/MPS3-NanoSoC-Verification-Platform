# 8. End to end: an SD card, driven only through AXI
# =========================================================================== #
class SdHost:
    """What lane L2's firmware driver does, in Python, through the registers
    only: every byte is a DATA write, a STATUS poll and a DATA read."""

    def __init__(self, b: Bench):
        self.b = b

    async def byte(self, v=0xFF):
        return await self.b.xfer(v)

    async def bytes_wide(self, data: bytes = None, n: int = 0):
        """512-byte payloads in WIDE (32-bit) mode, MSB first = wire order."""
        await self.b.set_ctrl(wide=1)
        out = bytearray()
        words = (len(data) if data is not None else n) // 4
        for i in range(words):
            w = int.from_bytes(data[4 * i:4 * i + 4], "big") if data is not None else 0xFFFF_FFFF
            out += (await self.b.xfer(w, wide=True)).to_bytes(4, "big")
        await self.b.set_ctrl(wide=0)
        return bytes(out)

    async def send_cmd(self, index, arg, crc=None):
        await self.byte(0xFF)
        frame = [0x40 | index] + list(arg.to_bytes(4, "big"))
        frame.append(cmd_crc(index, arg) if crc is None else crc)
        for x in frame:
            await self.byte(x)

    async def r1(self, polls=9):
        r = 0xFF
        for _ in range(polls):
            r = await self.byte()
            if not r & 0x80:
                break
        return r

    async def cmd(self, index, arg, extra=0, crc=None):
        await self.send_cmd(index, arg, crc)
        r = await self.r1()
        tail = [await self.byte() for _ in range(extra)] if not r & 0x80 else []
        return r, tail

    async def token(self, polls=64):
        t = 0xFF
        for _ in range(polls):
            t = await self.byte()
            if t != 0xFF:
                break
        return t

    async def wait_not_busy(self):
        n = 0
        while await self.byte() != 0xFF:
            n += 1
            assert n < 200, "card busy forever"
        return n

    async def deselect(self):
        await self.b.set_ctrl(cs=0)
        await self.byte()

    async def power_up_clocks(self):
        await self.b.set_ctrl(en=1, cs=0, wide=0)
        for _ in range(10):                            # 80 clocks, CS high
            await self.byte()

    async def init(self):
        b = self.b
        await b.set_div(CLKDIV_RESET)                  # 400 kHz for init
        await self.power_up_clocks()
        await b.set_ctrl(cs=1)
        r, _ = await self.cmd(0, 0)
        assert r == R1_IDLE, f"CMD0 R1 0x{r:02X}"
        r, r7 = await self.cmd(8, 0x1AA, extra=4)
        assert r == R1_IDLE and r7 == [0x00, 0x00, 0x01, 0xAA], f"CMD8 {r:#x} {r7}"
        for _ in range(20):
            r, _ = await self.cmd(55, 0)
            assert r in (0x00, 0x01), f"CMD55 R1 0x{r:02X}"
            r, _ = await self.cmd(41, 0x4000_0000)     # HCS
            if r == 0x00:
                break
        else:
            raise AssertionError("ACMD41 never left idle")
        r, ocr = await self.cmd(58, 0, extra=4)
        assert r == 0x00, f"CMD58 R1 0x{r:02X}"
        await self.deselect()
        await b.set_div(3)                             # 12.5 MHz from here on
        return int.from_bytes(bytes(ocr), "big")

    async def read_block(self, lba):
        await self.b.set_ctrl(cs=1)
        r, _ = await self.cmd(17, lba)
        assert r == 0x00, f"CMD17 R1 0x{r:02X}"
        assert await self.token() == 0xFE, "no read data token"
        data = await self.bytes_wide(n=BLOCK)
        crc = (await self.byte() << 8) | await self.byte()
        await self.deselect()
        assert crc == crc16(data), f"read CRC16 0x{crc:04X} != 0x{crc16(data):04X}"
        return data

    async def write_block(self, lba, data):
        await self.b.set_ctrl(cs=1)
        r, _ = await self.cmd(24, lba)
        assert r == 0x00, f"CMD24 R1 0x{r:02X}"
        await self.byte(0xFF)                           # Nwr
        await self.byte(0xFE)
        await self.bytes_wide(data)
        await self.byte(0xFF)                           # CRC16: off in SPI mode
        await self.byte(0xFF)
        resp = await self.byte() & 0x1F
        assert resp == DATA_RESP_ACCEPTED, f"data response 0x{resp:02X}"
        busy = await self.wait_not_busy()
        await self.deselect()
        return busy


