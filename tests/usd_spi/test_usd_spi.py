def _param(dut, name):
    """An elaborated parameter, read back from the simulator."""
    try:
        return int(getattr(dut, name).value)
    except Exception as exc:     # pragma: no cover - simulator-dependent
        raise AssertionError(
            f"cannot read parameter {name} from the DUT ({exc}); this bench "
            "reads the elaborated value instead of restating it") from exc


class Bench:
    def __init__(self, dut):
        self.dut = dut
        self.clk = dut.s_axi_aclk
        self.aw = len(dut.s_axi_awaddr)
        assert self.aw in (12, 32), f"unexpected C_S_AXI_ADDR_WIDTH {self.aw}"
        # At 32 bits the interconnect hands the slave the FULL system address;
        # drive it exactly so (the width-32 decode escape, tests/csr_decode_width).
        self.base = USD_BASE if self.aw == 32 else 0
        self.deb = _param(dut, "DEBOUNCE_CYCLES")
        assert _param(dut, "C_S_AXI_ADDR_WIDTH") == self.aw
        self.axi = AxiLiteMaster.from_dut(dut)
        self.ctrl = 0
        self.div = CLKDIV_RESET
        self.cd_pol = 0
        dut._log.info(f"usd_spi elaborated at C_S_AXI_ADDR_WIDTH={self.aw} "
                      f"(base 0x{self.base:08X}), DEBOUNCE_CYCLES={self.deb}")

    # -- register access ------------------------------------------------- #
    async def wr(self, off, val, strb=0xF):
        resp = await self.axi.write(self.base + off, val, strb)
        assert resp == 0, f"BRESP {resp} writing 0x{off:02X}"

    async def rd(self, off):
        data, resp = await self.axi.read(self.base + off)
        assert resp == 0, f"RRESP {resp} reading 0x{off:02X}"
        return data

    async def set_ctrl(self, en=None, cs=None, wide=None, cd_pol=None, cd_ignore=None):
        bits = {CTRL_EN: en, CTRL_CS: cs, CTRL_WIDE: wide,
                CTRL_CD_POL: cd_pol, CTRL_CD_IGNORE: cd_ignore}
        for bit, val in bits.items():
            if val is not None:
                self.ctrl = (self.ctrl | bit) if val else (self.ctrl & ~bit)
        if cd_pol is not None:
            self.cd_pol = 1 if cd_pol else 0
        await self.wr(USD_CTRL, self.ctrl)

    async def set_div(self, div):
        self.div = div
        await self.wr(USD_CLKDIV, div)

    async def status(self):
        return await self.rd(USD_STATUS)

    async def clear_sticky(self):
        await self.wr(USD_STATUS, ST_STICKY)

    async def cycles(self, n):
        """Wait n aclk cycles without a Python trigger per cycle."""
        await Timer(n * CLK_NS, unit="ns")

    # -- card detect ------------------------------------------------------- #
    def ncd_level(self, present):
        """USD_NCD pin level that means `present` under the current CD_POL."""
        return (1 if present else 0) if self.cd_pol else (0 if present else 1)

    async def insert_card(self):
        self.dut.usd_ncd_i.value = self.ncd_level(True)
        await self.cycles(self.deb + 6)
        assert await self.status() & ST_CD_PRESENT, "card inserted but CD_PRESENT=0"

    async def remove_card(self):
        self.dut.usd_ncd_i.value = self.ncd_level(False)

    # -- shifting --------------------------------------------------------- #
    def xfer_cycles(self, bits):
        return bits * 2 * (self.div + 1)

    async def wait_idle(self, bits):
        await self.cycles(self.xfer_cycles(bits))
        for _ in range(64):
            st = await self.status()
            if not st & ST_BUSY:
                return st
        raise AssertionError("BUSY never cleared")

    async def xfer(self, value, wide=False):
        """One shift through DATA, exactly as firmware does it. Assumes CTRL.WIDE
        already matches `wide`."""
        await self.wr(USD_DATA, value)
        st = await self.wait_idle(32 if wide else 8)
        assert not st & (ST_OVR | ST_ABORT), f"transfer flagged STATUS=0x{st:02X}"
        return await self.rd(USD_DATA)


async def bring_up(dut, card_present=False):
    # impl="gpi": the clock toggles inside the simulator's GPI layer, not in a
    # Python coroutine. cocotb only picks it by itself for simulators that set
    # COCOTB_TRUST_INERTIAL_WRITES; under VCS the Python clock costs ~100 us per
    # aclk, and the shipped 10 ms debounce is 1e6 of them. Nothing in this bench
    # writes a signal in the same timestep as the clock edge it depends on (the
    # BFM and the card-detect pulses write after an edge or mid-cycle), so the
    # ordering caveat behind that default does not apply.
    cocotb.start_soon(Clock(dut.s_axi_aclk, CLK_NS, unit="ns", impl="gpi").start())
    for name in ("awaddr", "awprot", "awvalid", "wdata", "wstrb", "wvalid",
                 "bready", "araddr", "arprot", "arvalid", "rready"):
        getattr(dut, f"s_axi_{name}").value = 0
    dut.usd_dat0_i.value = 1                         # pulled up, nothing driving
    dut.usd_ncd_i.value = 0 if card_present else 1   # reset polarity: low = card
    dut.s_axi_aresetn.value = 0
    await ClockCycles(dut.s_axi_aclk, 5)
    dut.s_axi_aresetn.value = 1
    await RisingEdge(dut.s_axi_aclk)
    return Bench(dut)


def oes(dut):
    return (int(dut.usd_clk_oe.value), int(dut.usd_cmd_oe.value),
            int(dut.usd_dat3_oe.value))


class PadWatch:
    """Background monitor: records every moment ANY output-enable is 1, and
    every SCK edge (driven or not). Event-driven (value changes, not a per-cycle
    poll), so it costs nothing over a 10 ms debounce window and still sees a
    one-cycle glitch. Runs concurrently with the AXI traffic, so the window
    includes the writes themselves."""

    def __init__(self, dut):
        self.dut = dut
        self.driven = []               # [(t_ns, (clk_oe, cmd_oe, dat3_oe))]
        self.sck_edges = 0
        self._tasks = []

    @property
    def first_driven(self):
        return self.driven[0] if self.driven else None

    def start(self):
        self._note()
        self._tasks = [cocotb.start_soon(self._oe()), cocotb.start_soon(self._sck())]
        return self

    def stop(self):
        for t in self._tasks:
            t.cancel()

    def _note(self):
        o = oes(self.dut)
        if any(o):
            self.driven.append((get_sim_time(unit="ns"), o))

    async def _oe(self):
        d = self.dut
        while True:
            await First(ValueChange(d.usd_clk_oe), ValueChange(d.usd_cmd_oe),
                        ValueChange(d.usd_dat3_oe))
            self._note()

    async def _sck(self):
        while True:
            await ValueChange(self.dut.usd_clk_o)
            self.sck_edges += 1


class RawSpiSlave:
    """A plain SPI mode-0 slave at the pads (no SD protocol): records MOSI and
    the time of every SCK edge, and shifts `reply` out MSB first, moving MISO
    `tod_ns` after each falling edge. Ignores CS, so it sees every clock."""

    def __init__(self, dut, reply: int, nbits: int, tod_ns: float = 2.0):
        self.dut = dut
        self.bits = [(reply >> (nbits - 1 - i)) & 1 for i in range(nbits)]
        self.tod_ns = tod_ns
        self.mosi = []
        self.rise_t = []
        self.fall_t = []
        self.mosi_change_t = []
        self._i = 0
        dut.usd_dat0_i.value = self.bits[0]
        self._tasks = [cocotb.start_soon(self._rise()), cocotb.start_soon(self._fall()),
                       cocotb.start_soon(self._mosi_watch())]

    def stop(self):
        for t in self._tasks:
            t.cancel()
        self.dut.usd_dat0_i.value = 1

    async def _rise(self):
        while True:
            await RisingEdge(self.dut.usd_clk_o)
            self.rise_t.append(get_sim_time(unit="ns"))
            self.mosi.append(int(self.dut.usd_cmd_o.value))

    async def _fall(self):
        while True:
            await FallingEdge(self.dut.usd_clk_o)
            self.fall_t.append(get_sim_time(unit="ns"))
            self._i += 1
            if self._i < len(self.bits):
                bit = self.bits[self._i]
                if self.tod_ns:
                    await Timer(self.tod_ns, unit="ns")
                self.dut.usd_dat0_i.value = bit

    async def _mosi_watch(self):
        while True:
            await ValueChange(self.dut.usd_cmd_o)
            self.mosi_change_t.append(get_sim_time(unit="ns"))

    def mosi_word(self):
        v = 0
        for bit in self.mosi:
            v = (v << 1) | bit
        return v


