CLK_NS = 10                      # shell_clk: 100 MHz
USD_BASE = 0x44A4_0000           # the page the BD assigns (shell_bd.tcl ;# USD)

# --- the lane contract ----------------------------------------------------- #
USD_ID, USD_CTRL, USD_CLKDIV, USD_DATA, USD_STATUS = 0x00, 0x04, 0x08, 0x0C, 0x10
CTRL_EN, CTRL_CS, CTRL_WIDE, CTRL_CD_POL, CTRL_CD_IGNORE = 1, 2, 4, 8, 16
ST_BUSY, ST_CD_PRESENT, ST_CD_RAW = 1, 2, 4
ST_CD_CHANGED, ST_OVR, ST_ABORT = 8, 16, 32
ST_STICKY = ST_CD_CHANGED | ST_OVR | ST_ABORT
ID_VALUE = 0x5553_4431           # "USD1"
CLKDIV_RESET = 124               # 400 kHz at 100 MHz

# D13 landed in the BD: the generated map must say exactly what this bench drives.
