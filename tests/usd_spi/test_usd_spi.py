@cocotb.test(skip=NO_RTL)
async def test_sd_end_to_end(dut):
    """Insert a card, init it, read its CSD, read a block, write a block, read
    it back — every step through AXI only, against the SD SPI-mode model."""
    b = await bring_up(dut, card_present=False)
    card = _card(dut)
    lba_r, lba_w = 2048, 2048 + 9                  # partition start, and slot-ish
    seeded = bytes(random.Random(1).getrandbits(8) for _ in range(BLOCK))
    card.write_block(lba_r, seeded)

    await b.insert_card()
    await b.clear_sticky()
    host = SdHost(b)

    ocr = await host.init()
    assert ocr & (1 << 31) and ocr & (1 << 30), f"OCR 0x{ocr:08X}: not ready SDHC (CCS)"
    assert card.spi_mode and card.ready

    # CSD v2 -> capacity.
    await b.set_ctrl(cs=1)
    r, _ = await host.cmd(9, 0)
    assert r == 0x00
    assert await host.token() == 0xFE
    csd = bytes([await host.byte() for _ in range(16)])
    crc = (await host.byte() << 8) | await host.byte()
    await host.deselect()
    assert crc == crc16(csd) and csd[0] >> 6 == 1, f"CSD {csd.hex()}"
    c_size = ((csd[7] & 0x3F) << 16) | (csd[8] << 8) | csd[9]
    assert (c_size + 1) * 1024 == card.capacity_blocks

    got = await host.read_block(lba_r)
    assert got == seeded, "CMD17 returned the wrong data"

    payload = bytes(random.Random(2).getrandbits(8) for _ in range(BLOCK))
    busy = await host.write_block(lba_w, payload)
    assert busy > 0, "the card's write busy was never observed"
    assert card.writes == [lba_w] and bytes(card.blocks[lba_w]) == payload

    assert await host.read_block(lba_w) == payload, "read-back mismatch"
    assert await host.read_block(lba_r) == seeded, "a neighbouring block changed"

    st = await b.status()
    assert not st & (ST_OVR | ST_ABORT), f"STATUS 0x{st:02X}"
    assert card.errors == [], card.errors
    card.stop()


