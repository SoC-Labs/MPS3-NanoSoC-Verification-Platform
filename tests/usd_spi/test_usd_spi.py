async def _pulse_ncd(b, level, ncycles):
    """Drive USD_NCD to `level` for exactly `ncycles` aclk samples. The pin
    moves MID-cycle (half a period after an edge) so no edge can race the
    write and the sample count is exact."""
    await RisingEdge(b.clk)
    await Timer(CLK_NS // 2, unit="ns")
    b.dut.usd_ncd_i.value = level
    await Timer(ncycles * CLK_NS, unit="ns")
    b.dut.usd_ncd_i.value = 1 - level


@cocotb.test(skip=NO_RTL)
async def test_cd_debounce_glitch_ignored_then_accepted(dut):
    """A card-detect glitch of DEBOUNCE_CYCLES-1 aclk is invisible (CD_RAW sees
    it, CD_PRESENT and CD_CHANGED do not); a level held DEBOUNCE_CYCLES is a
    card. CD_CHANGED is sticky and W1C, and removal sets it again."""
    b = await bring_up(dut, card_present=False)
    # CD_RAW follows the pin (2-FF sync, no debounce): read it DURING the glitch.
    glitch = cocotb.start_soon(_pulse_ncd(b, 0, b.deb - 1))
    await b.cycles(6)
    st = await b.status()
    assert not st & ST_CD_RAW, f"CD_RAW did not follow the pin (STATUS=0x{st:02X})"
    assert not st & (ST_CD_PRESENT | ST_CD_CHANGED)
    await glitch
    await b.cycles(8)
    st = await b.status()
    assert not st & (ST_CD_PRESENT | ST_CD_CHANGED), (
        f"a {b.deb - 1}-cycle glitch got through the debounce (STATUS=0x{st:02X})")

    # Held: accepted.
    dut.usd_ncd_i.value = 0
    await b.cycles(b.deb + 4)
    st = await b.status()
    assert st & ST_CD_PRESENT and st & ST_CD_CHANGED and not st & ST_CD_RAW, f"0x{st:02X}"

    # W1C: writing 0 does nothing, writing another sticky bit does nothing.
    await b.wr(USD_STATUS, 0)
    await b.wr(USD_STATUS, ST_OVR | ST_ABORT)
    assert await b.status() & ST_CD_CHANGED
    await b.wr(USD_STATUS, ST_CD_CHANGED)
    st = await b.status()
    assert not st & ST_CD_CHANGED and st & ST_CD_PRESENT

    # A removal glitch is ignored too; a real removal sets CD_CHANGED again.
    await _pulse_ncd(b, 1, b.deb - 1)
    dut.usd_ncd_i.value = 0
    await b.cycles(8)
    st = await b.status()
    assert st & ST_CD_PRESENT and not st & ST_CD_CHANGED, f"0x{st:02X}"
    dut.usd_ncd_i.value = 1
    await b.cycles(b.deb + 4)
    st = await b.status()
    assert not st & ST_CD_PRESENT and st & ST_CD_CHANGED and st & ST_CD_RAW


