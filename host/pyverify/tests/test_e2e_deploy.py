def test_cli_deploy_wrong_static_id_exits_1_and_pushes_nothing(tmp_path, capsys):
    """The shell reports a different static_id on ping, so validation
    fails HOST-side: exit 1, a clean one-line stderr, and — critically —
    no bitstream bytes ever cross the wire."""
    overlay_dir = make_synthetic_overlay(tmp_path)
    with FakeShell.ephemeral(static_id=0xDEADBEEF) as fake:
        rc = main(deploy_argv(fake, overlay_dir, "tftp"))
        captured = capsys.readouterr()
        assert rc == 1
        assert "static_id mismatch" in captured.err
        assert "Traceback" not in captured.err
        assert captured.out == ""
        assert fake.push_events == []
        assert fake.swaps == []


def test_facade_deploy_wrong_static_id_raises_swap_error(tmp_path):
    make_synthetic_overlay(tmp_path)
    with FakeShell.ephemeral(static_id=0xDEADBEEF) as fake:
        with Mps3Board(
            fake.host,
            control_port=fake.control_port,
            tftp_port=fake.tftp_port,
            tcp_push_port=fake.raw_tcp_port,
            overlay_root=tmp_path,
        ) as board:
            with pytest.raises(SwapError, match="static_id mismatch"):
                board.deploy("nanosoc")
            assert board.last_deploy is None
        assert fake.push_events == []
        assert fake.swaps == []
