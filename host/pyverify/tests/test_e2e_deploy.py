"""E2E-1 (W-E2E convergence gate): full ``deploy`` end-to-end against the
FakeShell — CLI (``python -m pyverify.cli deploy``) and facade
(:meth:`pyverify.board.Mps3Board.deploy`) paths, over both push transports
(TFTP and raw TCP), plus the wrong-static_id rejection path.

Two overlay sources:

- **The real KU115 overlay triples** in ``fpga/dfx/overlay/<rm>/``
  (generated by ``fpga/dfx/gen_manifest.py`` from actual bitstreams). Payload
  sizes are read **from each RM's manifest on disk**; the running-shell
  ``static_id`` the FakeShell must report is read from the shell's OWN
  generated identity source, ``fpga/dfx/overlay/mps3_shell_static_id.c`` —
  *not* from an overlay's manifest, which only records the static that overlay
  was built AGAINST (see :func:`_real_static_id`). Nothing is hardcoded, so a
  DFX rebuild against a new static shell (which mints a fresh ``static_id``
  and, with compression, different sizes) re-keys these tests automatically.
  The ``.bin`` payloads are gitignored, so these tests ``pytest.skip`` cleanly
  on a fresh clone where only the manifest (or nothing) is present.
- **A small synthetic triple** built in ``tmp_path`` with a
  gen_manifest.py-compatible ``manifest.json`` — always runs, so CI never
  goes coverage-dark on the E2E path.

Everything crosses real sockets on 127.0.0.1 ephemeral ports: the CLI/
facade drive the production ``ShellClient`` + ``BitstreamPusher`` against
the FakeShell's control/TFTP/raw-TCP servers, and the swap is verified by
the same :mod:`pyverify.testing.swap_model` port of the firmware FSM.

**No ``rm_id`` is hard-coded here.** Under the v2 encoding
(docs/VERSIONING_PLAN.md §3.2) an ``rm_id`` is
``{ver_major[31:24], ver_minor[23:16], design_id[15:0]}``, so it legitimately
changes on every design *version* bump — a literal would re-break these tests
forever. Instead each test asserts the two things it actually means:

1. **the round trip** — the board reports back exactly the id that the pushed
   overlay's own ``manifest.json`` declared (:func:`_real_rm_id`); and
2. **the design** — the version-stable low half (``rm_id & 0xFFFF``) is the
   design we asked for (``DESIGN_ID_NANOSOC`` / ``DESIGN_ID_LED``), so pushing
   the wrong overlay still fails loudly.

``scripts/harness_gates/check_rm_id_literals.py`` enforces this repo-wide.
"""
