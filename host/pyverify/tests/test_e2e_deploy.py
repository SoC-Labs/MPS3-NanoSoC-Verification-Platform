REPO_ROOT = Path(__file__).resolve().parents[3]
REAL_OVERLAY_ROOT = REPO_ROOT / "fpga" / "dfx" / "overlay"

#: The shell's OWN generated identity source: the strong
#: ``mps3_shell_static_id()`` override that ``make -C fpga/dfx overlays`` emits
#: and A3 links into the shell firmware image. This — not any per-RM overlay
#: manifest — is the authoritative record of the static_id the *running shell*
#: reports on ping (fpga/dfx/Makefile; net-protocol.md ping.shell_id). A DFX
#: rebuild rewrites it, so reading it here re-keys the tests with no edit.
SHELL_STATIC_ID_C = REAL_OVERLAY_ROOT / "mps3_shell_static_id.c"

#: Pulls the literal out of ``uint32_t mps3_shell_static_id(void) { return
#: 0x...; }`` — anchored to the function body (``)`` then ``{`` then
#: ``return``) so the file's own header comment, which also names
#: ``mps3_shell_static_id()``, cannot match. Tolerates the ``UL``/``u`` suffix
#: the Makefile / gen_greybox_blob.py emit (captured group stops at the digits).
_SHELL_STATIC_ID_RE = re.compile(
    r"mps3_shell_static_id\s*\([^)]*\)\s*\{\s*return\s+(0[xX][0-9A-Fa-f]+)",
    re.DOTALL,
)

PKG_ROOT = Path(__file__).resolve().parents[1]  # host/pyverify (has pyverify/)


def _real_manifest(rm_name: str = "nanosoc") -> dict | None:
    """Parse the real overlay's manifest.json if present, else None.

    The single source of truth for the real triple's ``static_id`` and
    payload sizes: a DFX rebuild against a new static shell rewrites this
    file (new ``static_id``, new compressed sizes) and the tests below track
    it with no edit. Returns None on a fresh clone (manifest absent) so the
    real-overlay tests skip rather than key off a stale constant.
    """
    manifest = REAL_OVERLAY_ROOT / rm_name / "manifest.json"
    if not manifest.is_file():
        return None
    try:
        return json.loads(manifest.read_text())
    except (json.JSONDecodeError, OSError):
        return None


def _real_static_id() -> int:
    """The static_id the *running shell* reports on ping — what the FakeShell
    must claim so that CURRENT overlays validate against it (and STALE ones
    honestly do not).

    Read from the shell's OWN identity source
    (``fpga/dfx/overlay/mps3_shell_static_id.c``), NOT from a per-RM
    ``overlay/<rm>/manifest.json``. An overlay manifest records the static the
    overlay was *built against*; only ``mps3_shell_static_id.c`` records what
    the *running shell itself* reports on ping. Seeding the FakeShell from an
    overlay manifest is a category error: when that overlay is stale relative
    to the shell, every CURRENT overlay then appears to mismatch and the
    failure blames the wrong RM. This function is rm-independent by design.

    No hardcoded id and no fall-back constant: the file is git-tracked (only
    the ``.bin`` payloads are gitignored), and every caller runs
    ``real_overlay_dir()`` first — which skips on a fresh clone before this is
    reached — so a missing/garbled file is a real defect worth failing on, not
    something to paper over with a stale literal.
    """
    text = SHELL_STATIC_ID_C.read_text()
    match = _SHELL_STATIC_ID_RE.search(text)
    if match is None:
        raise ValueError(
            f"could not parse a static_id from {SHELL_STATIC_ID_C} "
            "(expected `uint32_t mps3_shell_static_id(void) {{ return 0x...; }}`; "
            "regenerate with `make -C fpga/dfx overlays`)"
        )
    return int(match.group(1), 0)


def _overlay_built_against_static_id(rm_name: str = "nanosoc") -> int:
    """The static_id an overlay declares it was BUILT AGAINST (its manifest's
    ``static_id``) — i.e. the shell that overlay is valid for.

    Deliberately NOT :func:`_real_static_id`. Used only to seed the FakeShell
    in the *single-overlay* happy-path tests, where a shell the
    overlay-under-test is compatible with is a PRECONDITION for exercising the
    real transport/swap mechanics — not the thing under test. Those tests carry
    no cross-overlay constraint, so they stay green regardless of any one
    overlay's freshness. The multi-overlay
    ``..._led_then_nanosoc_second_swap`` test is the one that pins overlays
    against the REAL running shell (:func:`_real_static_id`) and so honestly
    fails while ``nanosoc`` is stale — that mismatch is surfaced there, once,
    not smeared across every real-payload mechanics test.

    Only reached after ``real_overlay_dir()`` has confirmed the manifest
    exists, so a None here is a logic error, not a fresh clone.
    """
    m = _real_manifest(rm_name)
    assert m is not None, (
        "single-overlay test seeded its shell before real_overlay_dir() "
        "confirmed the manifest exists"
    )
    return int(m["static_id"], 0)


def real_overlay_dir(rm_name: str = "nanosoc") -> Path:
    """The real overlay triple for ``rm_name``, or skip: the ``.bin``
    payloads are gitignored (fresh clones have at most the manifest)."""
    directory = REAL_OVERLAY_ROOT / rm_name
    manifest_path = directory / "manifest.json"
    if not manifest_path.is_file():
        pytest.skip(f"real overlay not present: {manifest_path} (fresh clone?)")
    manifest = json.loads(manifest_path.read_text())
    for kind in ("clearing", "partial"):
        payload = directory / manifest[kind]["file"]
        if not payload.is_file():
            pytest.skip(
                f"real overlay {kind} payload not present: {payload} "
                "(bitstream .bins are gitignored)"
            )
    return directory


def _real_rm_id(rm_name: str = "nanosoc") -> int:
    """The rm_id the real overlay's manifest DECLARES — i.e. the value the
    board must read back at ``DFXCTL.RM_ID`` after this exact artefact lands.

    Derived, never hard-coded. Since the v2 encoding (VERSIONING_PLAN.md §3.2)
    an rm_id is ``{ver_major[31:24], ver_minor[23:16], design_id[15:0]}``, so
    it *legitimately changes on every design version bump* — nanosoc v1.0 is
    0x01000001, v1.1 will be 0x01010001. A literal here would be a maintenance
    landmine that re-breaks these tests on every bump, forever.

    Reading it from the manifest is also the *honest* subject of these tests:
    the round trip is "deploy pushes overlay X, and the board reports the id
    X's own manifest declared". The manifest is what the pusher puts in the
    partial's 24-byte header and what firmware's ``step_verify()`` compares
    ``DFXCTL.RM_ID`` against — so this asserts the real contract end to end.
    The *stable* half of the id is pinned separately (see DESIGN_ID_*) so a
    swap that lands the WRONG DESIGN still fails loudly.

    Called only after ``real_overlay_dir()`` has confirmed the manifest exists.
    """
    m = _real_manifest(rm_name)
    assert m is not None, "real manifest vanished after real_overlay_dir() check"
    return int(m["rm_id"], 0)


#: The version-STABLE half of each real RM's identity: ``rm_id & 0xFFFF``
#: (:mod:`pyverify.rm_id`). These are legitimate hard pins — a design_id is
#: fixed for the life of the design, and re-numbering one is a deliberate
#: breaking change (uart_echo, 2026-07-14). Pinning them is what makes these
#: tests still fail loudly if the deploy lands the WRONG DESIGN, while the
#: version half is derived from the manifest and so survives version bumps.
#: ``scripts/harness_gates/check_rm_id_literals.py`` machine-checks these two
#: literals against ``fpga/dfx/rm_list.tcl``, so a re-numbering cannot leave a
#: stale pin here undetected.
DESIGN_ID_NANOSOC = 0x0001
DESIGN_ID_LED = 0x001E

#: An arbitrary static_id for synthetic overlays — decoupled from any real
#: shell build (the synthetic test configures the FakeShell with the same
#: value, so it only needs to be self-consistent).
SYNTHETIC_STATIC_ID = 0x2F458F06

#: The synthetic overlay's id. Its design half (0x7A57) is deliberately OUTSIDE
#: the allocated design_id range in ``fpga/dfx/rm_list.tcl`` — a fixture must
#: never masquerade as a real design. (It used to be 0x0000_0001, which both
#: claimed to *be* nanosoc and, post-v2, is not even a well-formed nanosoc id.)
#: Version half v1.0, so it is a structurally valid v2 rm_id.
SYNTHETIC_RM_ID = 0x0100_7A57


def make_synthetic_overlay(
    root: Path,
    *,
    rm_name: str = "nanosoc",
    rm_id: int = SYNTHETIC_RM_ID,
    static_id: int = SYNTHETIC_STATIC_ID,
    clearing_payload: bytes = b"\xC1\x0E\xA2\x00" * 32,
    partial_payload: bytes = b"\xB1\x75\x00\x0D" * 96,
) -> Path:
    """A tiny fake triple whose manifest.json matches gen_manifest.py's
    output byte-for-byte in shape (same keys, same contract filenames,
    same '0x'-lowercase-hex crc32 strings)."""
    directory = root / rm_name
    directory.mkdir(parents=True)
    partial_name = f"{rm_name}.bin"
    clearing_name = f"{rm_name}_clear.bin"
    (directory / clearing_name).write_bytes(clearing_payload)
    (directory / partial_name).write_bytes(partial_payload)
    manifest = {
        "schema": 1,
        "static_id": f"0x{static_id:08X}",
        "rm_id": f"0x{rm_id:08x}",
        "rm_name": rm_name,
        "clearing": {
            "file": clearing_name,
            "len": len(clearing_payload),
            "crc32": f"0x{zlib.crc32(clearing_payload) & 0xFFFFFFFF:08x}",
        },
        "partial": {
            "file": partial_name,
            "len": len(partial_payload),
            "crc32": f"0x{zlib.crc32(partial_payload) & 0xFFFFFFFF:08x}",
        },
        "built": "2026-07-06",
        "vivado": "2024.1",
    }
    (directory / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    return directory


def deploy_argv(fake: FakeShell, overlay_dir: Path, transport: str) -> list[str]:
    argv = [
        "deploy", "--host", fake.host, "--overlay", str(overlay_dir),
        "--control-port", str(fake.control_port),
    ]
    if transport == "tftp":
        argv += ["--tftp-port", str(fake.tftp_port)]
    else:
        argv += ["--pusher-transport", "tcp", "--src", "tcp",
                 "--tcp-push-port", str(fake.raw_tcp_port)]
    return argv


def assert_shell_saw_verified_deploy(
    fake: FakeShell, *, transport: str, rm_id: int, sizes: tuple[int, int],
) -> None:
    """Server-side truth: clearing-then-partial accepted on the expected
    transport with the expected byte counts, and the swap FSM ran to DONE."""
    assert [e.status for e in fake.push_events] == ["OK", "OK"]
    assert [e.transport for e in fake.accepted_pushes] == [transport, transport]
    assert [e.info.kind for e in fake.accepted_pushes] == [
        BitstreamKind.CLEARING, BitstreamKind.PARTIAL,
    ]
    assert [e.info.len_words * 4 for e in fake.accepted_pushes] == list(sizes)
    assert fake.swaps[-1]["final"] == "DONE"
    assert fake.current_rm_id == rm_id


