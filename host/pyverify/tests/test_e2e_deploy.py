def _real_sizes(rm_name: str = "nanosoc") -> tuple[int, int]:
    """(clearing, partial) byte lengths from the real manifest — tracks the
    compression the shell's constraints apply, so a rebuild re-keys the
    byte-count assertions with no edit. Called only after real_overlay_dir()
    has confirmed the manifest+payloads exist."""
    m = _real_manifest(rm_name)
    assert m is not None, "real manifest vanished after real_overlay_dir() check"
    return (m["clearing"]["len"], m["partial"]["len"])


@pytest.mark.parametrize("transport", ["tftp", "tcp"])
def test_cli_deploy_real_nanosoc_overlay(transport, capsys):
    """``python -m pyverify.cli deploy`` semantics via ``main(argv)``: the
    real 3.6 MB partial + 240 KB clearing cross the wire, the swap is
    accepted and verified, exit code 0, exactly one JSON object on stdout.

    The rm_id assertion is the ROUND TRIP — the board reports back exactly the
    id nanosoc's own manifest declared — plus a pin on the version-stable
    design half, so a deploy that lands the wrong DESIGN still fails loudly.
    """
    overlay_dir = real_overlay_dir("nanosoc")
    want_rm_id = _real_rm_id("nanosoc")
    assert rm_design_id(want_rm_id) == DESIGN_ID_NANOSOC, (
        "the nanosoc overlay's manifest does not declare the nanosoc design"
    )
    with FakeShell.ephemeral(static_id=_overlay_built_against_static_id("nanosoc")) as fake:
        rc = main(deploy_argv(fake, overlay_dir, transport))
        captured = capsys.readouterr()
        assert rc == 0
        assert captured.err == ""
        result = json.loads(captured.out)
        assert result == {
            "ok": True, "rm_id": format_rm_id(want_rm_id),
            "verified": True, "ltx_path": None,
        }
        assert_shell_saw_verified_deploy(
            fake, transport=transport, rm_id=want_rm_id, sizes=_real_sizes(),
        )


def test_cli_deploy_real_nanosoc_overlay_as_subprocess():
    """The literal headline command — a separate ``python -m pyverify.cli``
    process pushing the real overlay to the fake shell over real sockets."""
    overlay_dir = real_overlay_dir("nanosoc")
    want_rm_id = _real_rm_id("nanosoc")
    assert rm_design_id(want_rm_id) == DESIGN_ID_NANOSOC
    env = dict(os.environ)
    env["PYTHONPATH"] = str(PKG_ROOT) + os.pathsep + env.get("PYTHONPATH", "")
    with FakeShell.ephemeral(static_id=_overlay_built_against_static_id("nanosoc")) as fake:
        proc = subprocess.run(
            [sys.executable, "-m", "pyverify.cli"]
            + deploy_argv(fake, overlay_dir, "tftp"),
            capture_output=True, text=True, timeout=120, env=env,
        )
        assert proc.returncode == 0, proc.stderr
        assert json.loads(proc.stdout) == {
            "ok": True, "rm_id": format_rm_id(want_rm_id),
            "verified": True, "ltx_path": None,
        }
        assert_shell_saw_verified_deploy(
            fake, transport="tftp", rm_id=want_rm_id, sizes=_real_sizes(),
        )


@pytest.mark.parametrize("transport", ["tftp", "tcp"])
def test_facade_deploy_real_nanosoc_overlay(transport):
    """``Mps3Board.deploy`` (the notebook/"PYNQ experience" path) with the
    real overlay, resolved as a bare RM name against overlay_root."""
    real_overlay_dir("nanosoc")
    want_rm_id = _real_rm_id("nanosoc")
    assert rm_design_id(want_rm_id) == DESIGN_ID_NANOSOC
    with FakeShell.ephemeral(static_id=_overlay_built_against_static_id("nanosoc")) as fake:
        with Mps3Board(
            fake.host,
            control_port=fake.control_port,
            tftp_port=fake.tftp_port,
            tcp_push_port=fake.raw_tcp_port,
            transport=transport,
            overlay_root=REAL_OVERLAY_ROOT,
        ) as board:
            result = board.deploy("nanosoc", src=transport)
            assert result.verified is True
            assert int(result.rm_id, 0) == want_rm_id
            assert rm_design_id(result.rm_id) == DESIGN_ID_NANOSOC
            assert board.last_deploy is result
            assert result.reattach.shell_host == fake.host
            # ping now reports the new RM (net-protocol.md swap step 7).
            assert int(board.ping().rm_id, 0) == want_rm_id
        assert_shell_saw_verified_deploy(
            fake, transport=transport, rm_id=want_rm_id, sizes=_real_sizes(),
        )


def test_facade_deploy_real_led_then_nanosoc_second_swap():
    """Two consecutive real-overlay swaps (led -> nanosoc): the second one
    clears the first RM using the clearing cached from led's own push —
    the server-visible half of the I2 clearing-cache contract.

    This is the test that would catch a deploy pushing the WRONG overlay: each
    leg pins the version-stable design half (led 0x001E, nanosoc 0x0001) as
    well as round-tripping that leg's own manifest-declared id.
    """
    led_dir = real_overlay_dir("led")
    nanosoc_dir = real_overlay_dir("nanosoc")
    led_rm_id = _real_rm_id("led")
    nanosoc_rm_id = _real_rm_id("nanosoc")
    assert rm_design_id(led_rm_id) == DESIGN_ID_LED
    assert rm_design_id(nanosoc_rm_id) == DESIGN_ID_NANOSOC
    assert led_rm_id != nanosoc_rm_id, "the two legs must be distinguishable"
    with FakeShell.ephemeral(static_id=_real_static_id()) as fake:
        with Mps3Board(
            fake.host,
            control_port=fake.control_port,
            tftp_port=fake.tftp_port,
            tcp_push_port=fake.raw_tcp_port,
            overlay_root=REAL_OVERLAY_ROOT,
        ) as board:
            led = board.deploy(led_dir)
            assert led.verified and int(led.rm_id, 0) == led_rm_id
            assert rm_design_id(led.rm_id) == DESIGN_ID_LED
            nanosoc = board.deploy(nanosoc_dir)
            assert nanosoc.verified and int(nanosoc.rm_id, 0) == nanosoc_rm_id
            assert rm_design_id(nanosoc.rm_id) == DESIGN_ID_NANOSOC
        assert [s["final"] for s in fake.swaps] == ["DONE", "DONE"]
        assert fake.current_rm_id == nanosoc_rm_id
        assert fake._current_clearing.rm_id == nanosoc_rm_id  # cached for swap 3


